// ================================================================
// 1. LCD_Fill: 基础矩形区域填充
//    入参：(xsta, ysta) 左上角起点坐标, (xend, yend) 右下角终点坐标, *color_p 颜色指针
// ================================================================
void LCD_Fill(u16 xsta, u16 ysta, u16 xend, u16 yend, lv_color_t *color_p)
{          
    u16 i, j; 
    LCD_Address_Set(xsta, ysta, xend - 1, yend - 1); // 锁定显示开窗范围
    for(i = ysta; i < yend; i++)
    {													   	 	
        for(j = xsta; j < xend; j++)
        {
            LCD_WR_DATA(color_p->full);
            color_p++;
        }
    } 					  	    
}

// ================================================================
// 2. LCD_Color_Fill: LVGL 核心专用局部脏矩形极速刷屏通道
//
// 💡 硬件冲突与“色彩怪异/眩晕/反色”物理根治揭秘:
//    - 体系架构冲突：
//      1) STM32 Cortex-M4 内核属于【小端模式 (Little-Endian)】，16 位整数存储时低字节在先、高字节在后；
//      2) ST7796S 控制器的 SPI 引擎属于【大端接收 (Big-Endian)】，RGB565 像素流必须先收高字节 (R5-G3)，后收低字节 (G2-B5)。
//    - 眩晕/反色的根源：
//      若直接通过 SPI 发送原始显存数据，Red 与 Blue 分量的高低位被彻底错位打乱，导致正常仪表盘产生剧烈的蓝面偏色与视错觉眩晕。
//    - 极致性能解决方案 (单周期 REV16 流水线)：
//      在压入 SPI 发送队列前，对内存中的 16 位颜色字执行:
//          p[i] = (p[i] >> 8) | (p[i] << 8);
//      ★ Keil 编译器优化黑科技：在开启 -O2/-O3 优化后，ARM 编译器会把该循环直接识别并生成
//        ARM 单周期汇编指令 `REV16 r0, r0`！以纯硬件指令流水线完成翻转，0 额外 CPU 周期损耗！
//
// 结构化刷屏 4 步流程：
//    步骤 1: 计算待刷新区域尺寸 -> 宽度 × 高度 = 总像素数 (字节数 = 像素数 × 2)；
//    步骤 2: REV16 字节序流水线   -> 在局部行缓冲上极速翻转高低字节；
//    步骤 3: LCD_Address_Set()   -> 硬件地址开窗，锁定本次重绘脏矩形物理坐标；
//    步骤 4: LCD_Writ_Bus_Len()  -> SPI 突发连续写入 (直接冲刷入 ST7796 内部显存 GRAM)。
// ================================================================
void LCD_Color_Fill(u16 sx, u16 sy, u16 ex, u16 ey, lv_color_t *color)
{
    // ------- 1. 计算待刷新区域尺寸与像素总吞吐量 -------
    u16 width = ex - sx + 1;
    u16 height = ey - sy + 1;
    uint32_t total = (uint32_t)width * height;
    uint16_t *p = (uint16_t *)color;

    // ------- 2. 字节序极速翻转流水线 (单周期硬件 REV16) -------
    for(uint32_t i = 0; i < total; i++) {
        p[i] = (p[i] >> 8) | (p[i] << 8);
    }

    // ------- 3. 硬件开窗并锁定 ST7796 显示区域 -------
    LCD_Address_Set(sx, sy, ex, ey);

    // ------- 4. SPI 突发总线传输 (大块像素流直接灌入显存) -------
    LCD_Writ_Bus_Len((u8 *)color, total * 2);
}

